@st.cache_resource
def load_ocr():
    return easyocr.Reader(['bg', 'en'], gpu=False)

def normalize_text(text_list):
    full_text = " ".join(text_list).upper()
    # Уеднаквяваме кирилица и латиница
    full_text = full_text.replace("Е", "E").replace("3", "E").replace("О", "0")
    # Премахваме интервали за по-лесно засичане (напр. Е 250 -> E250)
    condensed_text = full_text.replace(" ", "")
    return full_text, condensed_text

