if uploaded_file:
    img = Image.open(uploaded_file).convert('RGB')
    
    # Подобряваме контраста за OCR
    enhancer = ImageEnhance.Contrast(img)
    img_processed = enhancer.enhance(1.8)
    
    st.image(img, caption="Снимка за анализ", use_container_width=True)
    
    try:
        reader = load_ocr()
        with st.spinner("Анализиране на рисковете..."):
            result = reader.readtext(np.array(img_processed), detail=0)
            text_normal, text_condensed = normalize_text(result)
            
            found_items = []
            for key, info in INGREDIENT_DATABASE.items():
                # Търсим ключа в нормалния текст или в слятия текст
                if key in text_normal or key in text_condensed:
                    found_items.append((key, info))

            if found_items:
                st.error(f"⚠️ Открити са {len(found_items)} вредни съставки!")
                for key, info in found_items:
                    with st.expander(f"🛑 {key}", expanded=True):
                        st.markdown(f"**Здравословен проблем:** {info['problem']}")
                        st.write(f"ℹ️ **Защо е опасно:** {info['desc']}")
                        st.success(f"💡 **Алтернатива:** {info['alt']}")
            else:
                st.balloons()
                st.success("✅ Не бяха открити опасни съставки от базата данни!")

    except Exception as e:
        st.error(f"Грешка при анализа: {e}")
